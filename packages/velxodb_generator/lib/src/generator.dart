/// Turns a [ModelSpec] into plain Dart source.
///
/// The output contains no schema objects, no closures and no reflection:
/// encoding and decoding are straight-line static methods, field ids are
/// `const`s, and index creation is generated as direct calls. Generation runs
/// in a tool process, never at application startup.
library;

/// Supported field kinds.
enum FieldKind {
  /// UTF-8 string.
  string,

  /// 64-bit integer.
  int64,

  /// Boolean.
  boolean,
}

/// What happens to referring documents when a referenced document is deleted.
enum ReferenceAction {
  /// Refuse the delete.
  restrict,

  /// Delete referring documents.
  cascade,
}

/// Declares one field of a generated model.
final class FieldSpec {
  /// Creates a field spec.
  const FieldSpec(
    this.name,
    this.id,
    this.kind, {
    this.indexed = false,
    this.nullable = false,
    this.defaultValue,
    this.target,
    this.onDelete = ReferenceAction.restrict,
  });

  /// Dart property name, also the document field name.
  final String name;

  /// Wire field id. Must be stable forever.
  final int id;

  /// Value kind.
  final FieldKind kind;

  /// Whether to create a secondary index.
  final bool indexed;

  /// Whether the field may be null.
  final bool nullable;

  /// Collection this field references, when it is a reference.
  ///
  /// A reference is always indexed (the index is the reverse lookup).
  final String? target;

  /// Delete behaviour for a reference field.
  final ReferenceAction onDelete;

  /// Value substituted when an older document does not have this field.
  ///
  /// Only meaningful for non-nullable fields; generating a default is what lets
  /// a new version read documents written by an older one.
  final Object? defaultValue;
}

/// Declares a model to generate.
final class ModelSpec {
  /// Creates a model spec.
  const ModelSpec({
    required this.className,
    required this.collectionName,
    required this.fields,
    required this.keyField,
    this.schemaId = 1,
    this.version = 1,
  });

  /// Generated Dart class name.
  final String className;

  /// Collection name used by `VelxoDatabase.collection`.
  final String collectionName;

  /// Fields in constructor order.
  final List<FieldSpec> fields;

  /// Name of the string field used as the primary key.
  final String keyField;

  /// Schema id written into document headers.
  final int schemaId;

  /// Schema version written into document headers.
  final int version;
}

/// Generates the Dart source for [spec].
String generateModel(ModelSpec spec) {
  final fields = spec.fields;
  final key = fields.firstWhere(
    (field) => field.name == spec.keyField,
    orElse: () => throw ArgumentError(
      'keyField ${spec.keyField} is not declared in ${spec.className}',
    ),
  );
  if (key.kind != FieldKind.string) {
    throw ArgumentError('keyField ${spec.keyField} must be a string');
  }
  // Field ids are the on-disk identity and the encoder requires ascending
  // order; catch a bad spec at generation time instead of at the first write.
  var previousId = 0;
  for (final field in fields) {
    if (field.id <= previousId) {
      throw ArgumentError(
        'field ${field.name} has id ${field.id}; ids must be positive and '
        'strictly ascending (previous was $previousId)',
      );
    }
    if (field.id > 0xFFFF) {
      throw ArgumentError(
        'field ${field.name} has id ${field.id}; maximum is 65535',
      );
    }
    previousId = field.id;
  }

  final out = StringBuffer();
  out.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.');
  out.writeln('// Generated by package:velxodb_generator.');
  out.writeln();
  out.writeln("import 'dart:convert';");
  out.writeln("import 'dart:typed_data';");
  out.writeln();
  out.writeln("import 'package:velxodb/serde.dart';");
  out.writeln("import 'package:velxodb/velxodb.dart';");
  out.writeln();
  out.writeln('/// Model for the `${spec.collectionName}` collection.');
  out.writeln('final class ${spec.className} {');
  out.writeln('  /// Creates a ${spec.className}.');
  out.writeln('  const ${spec.className}({');
  for (final field in fields) {
    if (field.nullable) {
      out.writeln('    this.${field.name},');
    } else if (field.defaultValue != null) {
      out.writeln('    this.${field.name} = ${_literal(field)},');
    } else {
      out.writeln('    required this.${field.name},');
    }
  }
  out.writeln('  });');
  out.writeln();
  for (final field in fields) {
    out.writeln('  /// ${field.name}.');
    out.writeln('  final ${_dartType(field)} ${field.name};');
    out.writeln();
  }
  out.writeln('  /// Schema id written into document headers.');
  out.writeln('  static const int documentSchemaId = ${spec.schemaId};');
  out.writeln();
  out.writeln('  /// Schema version written into document headers.');
  out.writeln('  static const int documentSchemaVersion = ${spec.version};');
  out.writeln();
  for (final field in fields) {
    out.writeln('  /// Wire id of `${field.name}`.');
    out.writeln('  static const int _${field.name}Id = ${field.id};');
  }
  out.writeln();
  out.writeln('  /// Primary key bytes for this model.');
  out.writeln(
    '  static Uint8List keyOf(${spec.className} value) => '
    'Uint8List.fromList(utf8.encode(value.${spec.keyField}));',
  );
  out.writeln();
  out.writeln('  /// Writes [value] into [builder].');
  out.writeln(
    '  static void encodeInto(${spec.className} value, DocBuilder builder) {',
  );
  for (final field in fields) {
    final method = switch (field.kind) {
      FieldKind.string => 'putString',
      FieldKind.int64 => 'putInt',
      FieldKind.boolean => 'putBool',
    };
    final expression = 'value.${field.name}';
    if (field.nullable) {
      out.writeln('    final ${field.name}Value = $expression;');
      out.writeln(
        '    if (${field.name}Value != null) '
        'builder.$method(_${field.name}Id, ${field.name}Value);',
      );
    } else {
      out.writeln('    builder.$method(_${field.name}Id, $expression);');
    }
  }
  out.writeln('  }');
  out.writeln();
  out.writeln('  /// Reads a ${spec.className} from [view].');
  out.writeln(
    '  static ${spec.className} decodeFrom(DocView view) => '
    '${spec.className}(',
  );
  for (final field in fields) {
    final getter = switch (field.kind) {
      FieldKind.string => 'getString',
      FieldKind.int64 => 'getInt',
      FieldKind.boolean => 'getBool',
    };
    final fallback = field.nullable
        ? ''
        : field.defaultValue == null
        ? '!'
        : ' ?? ${_literal(field)}';
    out.writeln('    ${field.name}: view.$getter(_${field.name}Id)$fallback,');
  }
  out.writeln('  );');
  out.writeln();
  out.writeln('  /// Creates the secondary indexes declared by this model.');
  out.writeln('  static void ensureIndexes(Collection collection) {');
  final indexed = fields.where((field) => field.indexed).toList();
  if (indexed.isEmpty) {
    out.writeln('    // No indexed fields.');
  } else {
    for (final field in indexed) {
      out.writeln(
        '    collection.createIndex(_${field.name}Id, ${_vxsType(field)});',
      );
    }
  }
  for (final field in fields) {
    final target = field.target;
    if (target == null) continue;
    final action = field.onDelete == ReferenceAction.cascade
        ? 'cascade'
        : 'restrict';
    out.writeln(
      "    collection.createReference(_${field.name}Id, '$target', "
      'onDelete: OnDelete.$action);',
    );
  }
  out.writeln('  }');
  out.writeln();
  out.writeln('  /// Opens the typed collection and ensures declared indexes.');
  out.writeln(
    '  static TypedCollection<${spec.className}> open(VelxoDatabase db) {',
  );
  out.writeln(
    "    final collection = db.collection('${spec.collectionName}');",
  );
  out.writeln('    ensureIndexes(collection);');
  out.writeln('    return TypedCollection<${spec.className}>(');
  out.writeln('      collection,');
  out.writeln('      encodeInto,');
  out.writeln('      decodeFrom,');
  out.writeln('      schemaId: documentSchemaId,');
  out.writeln('      version: documentSchemaVersion,');
  out.writeln('    );');
  out.writeln('  }');
  out.writeln('}');
  return out.toString();
}

String _dartType(FieldSpec field) {
  final base = switch (field.kind) {
    FieldKind.string => 'String',
    FieldKind.int64 => 'int',
    FieldKind.boolean => 'bool',
  };
  return field.nullable ? '$base?' : base;
}

String _vxsType(FieldSpec field) => switch (field.kind) {
  FieldKind.string => 'VxsType.string',
  FieldKind.int64 => 'VxsType.int64',
  FieldKind.boolean => 'VxsType.boolean',
};

String _literal(FieldSpec field) {
  final value = field.defaultValue;
  if (value == null) {
    throw ArgumentError('field ${field.name} has no default');
  }
  return switch (field.kind) {
    FieldKind.string => "'${_escape(value as String)}'",
    FieldKind.int64 => '${value as int}',
    FieldKind.boolean => value == true ? 'true' : 'false',
  };
}

String _escape(String value) => value
    .replaceAll(r'\', r'\\')
    .replaceAll("'", r"\'")
    .replaceAll(r'$', r'\$')
    .replaceAll('\n', r'\n');
